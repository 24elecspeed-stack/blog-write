            append("제목과 본문 어디에도 구·동·지역 이름을 절대 넣지 마 - 키워드에 지역명이 있어도 빼고 써.\n")
        } else {
            append("실제 사례형 글은 고객이 말한 증상, 점검으로 확인된 원인, 실제 작업 과정, 확인된 결과를 구분해. 입력되지 않은 단계는 추측해 채우지 마.\n")
