package com.keyword.research

// 서로 완전히 다른 12개의 글쓰기 스타일. 번호(1~12)를 선택하면 해당 지침이 요청문에 반영된다.
enum class WritingStyle(val number: Int, val label: String, val guidance: String) {
    FRIENDLY_REVIEW(1, "친근한 후기형",
        "실제로 경험한 사람이 후기를 남기듯이 쓰세요. 소제목마다 '~했더니', '~해봤는데' 같은 경험 서술형 어미를 최소 한 번씩 쓰고, " +
        "본문 안에 '처음엔 ~인 줄 알았는데 알고 보니 ~였다' 식으로 본인의 착각이나 발견 과정을 최소 한 번 넣으세요."),
    EXPERT_ANALYSIS(2, "전문가 분석형",
        "입력 자료에 실제 측정값이나 기준값이 제공된 경우에만 그 수치를 사용하세요. 수치가 없으면 절연저항, 전류값, 점검 주기 등을 임의로 만들지 마세요. " +
        "'~로 판단됩니다', '~로 확인됩니다' 같은 진단형 어미를 자주 쓰고, 근거 없이 단정하지 말고 '~한 경우 ~로 볼 수 있습니다' 식으로 조건-결론 구조로 설명하세요."),
    QNA(3, "Q&A형",
        "전체 소제목 4~6개 중 내용에 맞는 3개 이상을 질문 형태(예: 왜 이런 증상이 생길까요)로 만들고, 그 소제목 바로 아래 문단에서 그 질문에 직접 답하는 방식으로 본문을 전개하세요. " +
        "그리고 본문 맨 마지막에 실제로 'Q. 질문 / A. 답변' 형식의 질의응답을 3개 넣으세요 (각 Q와 A는 줄을 바꿔서 쓰고, Q/A 항목 사이도 빈 줄로 구분). 이 Q&A 3개는 절대 빠뜨리지 마세요."),
    COMPARISON(4, "비교표형",
        "최소 2개 이상의 소제목에서 서로 다른 원인이나 조치 방법을 나란히 비교하세요. 표나 마크다운 없이, " +
        "'A의 경우 ~하고, B의 경우 ~하다' 또는 '~와 달리 ~는' 같은 대비 문장으로 차이를 명확히 짚으세요. 비용이나 시간은 입력 자료에 실제 정보가 있을 때만 비교하세요."),
    STORYTELLING(5, "스토리텔링형",
        "실제 상황을 따라가는 사례 중심으로 전개합니다. 도입부에 구체적인 상황을 제시하고 이야기처럼 풀어가세요. " +
        "소제목도 확인 순서(문의 내용, 증상 확인, 원인 확인, 작업, 결과)를 따르는 느낌으로 짓고, 소리·상태·위치 같은 디테일은 사용자가 제공한 내용만 사용하세요."),
    BEGINNER_GUIDE(6, "초보자 가이드형",
        "전문 용어를 쓸 때마다 바로 다음 문장이나 괄호 없이 이어지는 말로 쉬운 말로 즉시 풀어서 설명하세요(예: 절연저항을 언급하면 바로 이어서 전선이 얼마나 전기를 잘 가두고 있는지를 뜻한다는 식으로 설명). " +
        "소제목도 어려운 용어 대신 '이게 왜 문제인지', '언제 불러야 하는지'처럼 질문/일상어로 쓰고, 독자가 직접 확인할 수 있는 행동을 문장으로 안내하세요."),
    NEWS_BRIEFING(7, "뉴스브리핑형",
        "한 문장은 최대 2줄을 넘기지 마세요. 형용사·부사(정말, 매우, 너무 등)를 거의 쓰지 말고 사실만 전달하세요. " +
        "소제목도 완전한 문장이 아니라 핵심 명사구로 짧게 지으세요(예: 원인 확인 절차, 조치 결과 같은 식). 감정적 표현이나 공감 문장은 넣지 마세요."),
    MYTH_BUSTING(8, "논쟁/반박형",
        "최소 3개의 소제목에서 '~라고 생각하기 쉽지만 실제로는 ~다' 또는 '~라는 말이 있지만 ~와는 다르다' 구조로 흔한 오해를 먼저 제시하고 바로잡으세요. " +
        "일반적으로 알려진 것과 실제 현장에서 확인된 것을 대비시키는 문장을 본문 곳곳에 넣으세요."),
    PERSONAL_ESSAY(9, "감성 에세이형",
        "1인칭 시점을 유지하고, 소제목 중 최소 2개는 감정이나 인상을 담은 표현으로 지으세요(예: 생각보다 복잡했던 이유). " +
        "입력 자료에 실제 날씨, 시간대, 현장 분위기가 있을 때만 감각적 묘사를 넣고, 제공되지 않은 상황은 만들지 마세요. 독자에게 직접 말을 거는 문장을 두 번 이상 넣으세요(예: ~한 적 있으신가요)."),
    CHECKLIST(10, "체크리스트형",
        "소제목 4~6개 자체를 독자가 직접 확인할 행동을 나타내는 짧은 문구로 만드세요(예: 먼저 확인할 차단기 상태, 다음으로 살필 콘센트 주변). " +
        "각 소제목 아래 본문에서 무엇을 안전하게 확인할지와 그 결과가 무엇을 의미하는지 설명하세요. 번호나 기호로 나열하지 말고 '먼저', '다음으로', '마지막으로' 같은 순서 표현을 자연스럽게 사용하세요."),
    INTERVIEW(11, "인터뷰형",
        "사용자가 실제 대화를 제공한 경우에만 고객과 기사가 나눈 대화 형식으로 구성하세요. 대화가 없다면 실제 대화처럼 꾸미지 말고, 소제목 4~6개 전부를 '고객이 궁금해할 질문'으로 짓고 그 아래 문단에서 답하는 방식으로 본문 전체를 구성하세요(Q&A형과 달리 끝부분에 별도 Q&A 블록을 넣지 말고, 소제목 자체가 전부 질문이어야 합니다). " +
        "질문 소제목마다 어투를 다르게 하세요(왜 그런지 묻는 질문, 언제 그런지 묻는 질문, 어떻게 해야 하는지 묻는 질문 등을 섞어서) - 같은 패턴의 질문만 반복하지 마세요."),
    TIMELINE(12, "타임라인형",
        "본문을 작업 순서 기록처럼 구성하세요. 입력 자료에 실제 시간이나 경과 시간이 있으면 그대로 사용하고, 없으면 '초기 확인', '원인 점검', '작업 후 확인'처럼 단계만 구분하세요. " +
        "소제목도 진행 단계(접수 내용, 초기 점검, 원인 파악, 조치, 결과 확인)를 나타내는 식으로 지으세요. 제공되지 않은 시간과 수치는 만들지 마세요.");

    companion object {
        fun byNumber(number: Int): WritingStyle = entries.first { it.number == number }
    }

    val headingRule: String
        get() = when (this) {
            FRIENDLY_REVIEW -> "경험의 흐름이 드러나는 친근한 소제목"
            EXPERT_ANALYSIS -> "증상, 판단 근거, 확인 기준을 구분하는 진단형 소제목"
            QNA -> "독자가 궁금해할 질문 형태의 소제목"
            COMPARISON -> "서로 다른 원인이나 확인 방법의 차이를 드러내는 비교형 소제목"
            STORYTELLING -> "상황 확인부터 결과까지 순서가 이어지는 소제목"
            BEGINNER_GUIDE -> "초보자가 바로 이해할 수 있는 쉬운 질문이나 행동형 소제목"
            NEWS_BRIEFING -> "핵심 사실만 담은 짧은 명사구 소제목"
            MYTH_BUSTING -> "흔한 오해와 실제 판단을 대비하는 소제목"
            PERSONAL_ESSAY -> "느낌과 발견 과정이 드러나는 소제목"
            CHECKLIST -> "먼저, 다음으로, 마지막으로의 확인 순서가 드러나는 행동형 소제목"
            INTERVIEW -> "고객이 실제로 궁금해할 내용을 묻는 질문형 소제목"
            TIMELINE -> "초기 확인부터 결과 확인까지 진행 단계를 나타내는 소제목"
        }
}

object PromptBuilder {

    fun defaultEditableRules(): String = """
        한 글에서는 고객 질문 하나만 해결해. 제목과 무관한 내용을 한꺼번에 넣지 마.
        제목은 공백 포함 28자 이내의 한 줄로 써. 핵심 키워드와 독자가 얻을 답만 간결하게 담고, 상황 설명은 꼭 필요한 말만 남겨. 불필요한 수식어를 늘이지 말고 과장·공포·최저가·완벽 같은 낚시 표현을 쓰지 마.
        첫 150자 안에 질문의 핵심 답과 가장 중요한 안전 조치를 먼저 제시해. 인사말이나 업체 소개로 시작하지 마.
        본문은 내용에 맞는 4~6개 소제목으로 나누고 각 소제목은 서로 다른 역할을 맡게 해.
        사용자가 제공하지 않은 원인, 측정값, 비용, 소요 시간, 날짜, 날씨, 고객 반응, 작업 내용, 작업 결과는 절대 만들지 마. 가능한 원인을 설명할 때도 실제 원인처럼 단정하지 마.
        전문 용어는 바로 쉬운 말로 풀고, 초보자도 한 번에 이해할 수 있는 짧고 구체적인 문장으로 써.
        키워드는 문맥에 필요한 곳에만 자연스럽게 사용하고 횟수를 맞추려고 반복하지 마. 경쟁 글의 문장과 구조를 복사하지 마.
