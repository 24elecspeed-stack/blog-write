        }
        if (informational) {
            append("마지막은 핵심 안전 기준 또는 판단 기준으로 끝내고 전화, 예약, 상담, 방문을 유도하지 마.\n")
        } else {
            append("마지막에는 전화, 예약, 상담 중 하나의 행동만 자연스럽게 안내해. 여러 행동을 동시에 요구하지 마.\n")
        }
    }

