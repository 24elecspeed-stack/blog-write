        if (informational) {
            append("정보형 글은 문제 상황, 가능한 원인, 안전한 확인 방법, 전문가 점검이 필요한 기준, 주의사항 순서로 구성해. 특정 현장을 방문하거나 작업한 것처럼 쓰지 마.\n")
