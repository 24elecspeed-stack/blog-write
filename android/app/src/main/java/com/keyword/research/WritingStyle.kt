        append("본문 한 문단은 최대 4문장까지만 써줘. 네 번째 문장이 마침표로 끝나면 Enter를 두 번 쳐서 빈 줄 하나를 만들고 다음 문단을 시작해. 한 문단을 5줄 이상 길게 이어 쓰지 마.\n")
    }

    fun systemInstruction(blogProfile: BlogProfileEntry, informational: Boolean, baseRules: String): String =
        formatRules(blogProfile) + "\n" + editorialRules(informational, baseRules)

    // "100% 출장 내용 없는 순수 정보성 글" 지침 - editorialRules()의 정보형 줄들보다 훨씬
    // 강하고 구체적이다(방문 서술 금지 예시 문구, 수리 과정 설명 통째로 금지 등). 원래
    // build()에서 정보형일 때만 덧붙이던 블록인데, "사진으로 글쓰기"도 사진은 그림으로만 쓰고
    // 글은 100% 정보성으로 써야 한다는 사용자 지시로 internal 함수로 떼어내 재사용한다.
    internal fun informationalGuardrails(): String = buildString {
        append("[정보성 글 안내 - 이 글은 상업적 홍보가 아니라 순수 정보 전달이 목적이야]\n")
        append("업체명, 전화번호, '문의주세요', '방문해주세요', '연락주세요' 같은 홍보·상업적 문구는 절대 넣지 마. ")
        append("특정 업체를 광고하듯 언급하지 말고, 누구나 읽어도 도움이 되는 일반적인 정보 전달 글로 써줘. ")
        append("아주 중요 - 절대 기사가 현장에 방문해서 점검하고 조치했다는 식의 '출장 후기'나 '방문 수리 사례'처럼 쓰지 마. ")
        append("'현장에 도착해서', '방문하여', '점검해보니', '확인해봤더니', '조치를 완료했습니다', '고객님 댁을 찾아가' 같은 1인칭 출장 서술·경험담은 절대 쓰지 마. ")
        append("아주 중요 - 기사가 방문했다는 서술만 빼는 게 아니라, 실제로 수리·조치를 진행하는 내용 자체를 통째로 빼줘. ")
        append("부품 교체, 배선 연결·분리, 차단기 교체, 분해·조립 같은 구체적인 수리 과정이나 방법은 1인칭이든 일반적인 설명이든 어떤 형태로도 절대 쓰지 마. ")
        append("해결책을 물어도 '전문가 점검이 필요합니다', '전문가에게 문의하세요' 정도로만 안내하고, 수리를 어떻게 하는지는 설명하지 마. ")
        append("특정 방문이나 특정 사례를 이야기하듯 서술하지 말고, 이 주제에 대한 원인·증상·안전한 확인법·예방법 같은 일반 지식을 설명하는 순수 정보성 글로만 써줘. ")
        append("위에서 고른 글쓰기 스타일 지침이 사례 중심 서술이나 수리 과정 설명을 요구하더라도, 이 정보성 글 규칙이 항상 우선한다.\n")
        append("아주 중요 - 제목 키워드나 참고 자료에 특정 구·동·지역 이름이 들어 있어도, 제목과 본문 어디에도 그 지역명을 절대 쓰지 마. ")
        append("지역명은 완전히 빼고 증상·원인·확인법·해결법이라는 주제 자체만으로 누구에게나 적용되는 일반적인 글로 써줘.\n\n")
    }

    fun build(
        keyword: String,
        competitorPosts: List<NaverBlogSearchApi.BlogPost>,
        style: WritingStyle,
        blogProfile: BlogProfileEntry,
        caseInfo: String? = null, // 출장 사례 정보(지역/동/증상) - 채워져 있으면 실제 사례처럼 반영
        // 로드맵의 "지수 쌓기 단계 - 정보성 글 비율 80% 유지" 수칙: 지수 올리는 기간에는 전화번호나
        // 홍보 문구 없이 순수 정보 글로 써서 스팸 로봇 감시를 피한다. 이 값이 true면 업체/전화번호
        // 홍보 문구를 넣지 말라는 지침이 추가되고, 블로그 문체 안내에서도 전화번호를 언급하지 않는다.
        informational: Boolean = false,
        baseRules: String = defaultEditableRules()
    ): String = buildString {
        val phone = blogProfile.phone
        append(formatRules(blogProfile)).append("\n")
        append(editorialRules(informational, baseRules)).append("\n")
        if (informational) {
            append(informationalGuardrails())
        }
        append("[제목 키워드]:$keyword\n\n")
        append("[매우 중요한 사용자 프롬프트]:\n")
        append("위 제목 키워드를 검색한 사람이 가장 먼저 알고 싶은 질문 하나에 정확히 답하는 전문적인 블로그 글을 작성해줘. ")
        append("소제목은 내용에 맞게 4개에서 6개로 구성하고, 답부터 제시한 뒤 근거와 확인 과정이 이어지게 해줘. 소제목은 별도의 줄에 평문 텍스트로만 써줘. ")
        append("블로그 글을 작성할 때 '서론', '본론', '결론'이라는 단어는 글에 포함하지 말아줘. ")
        append("마지막 소제목에 '정리하며', '마무리', '마치며' 같은 형식적인 요약 문구를 절대 쓰지 마. ")
        if (informational) {
            append("마지막 부분은 독자가 기억할 안전 기준이나 전문가 점검이 필요한 판단 기준을 담은 구체적인 소제목으로 끝내줘.\n\n")
        } else {
            append("마지막 부분은 입력 자료로 확인된 작업 결과나 재발 방지 확인점을 담은 구체적인 소제목으로 끝내줘.\n\n")
        }

        if (!caseInfo.isNullOrBlank()) {
            append(caseInfo).append("\n")
        }

        if (competitorPosts.isNotEmpty()) {
            append("[최근 경쟁 블로그 글 - 제목과 구조를 그대로 베끼지 말고, 참고만 하세요]\n")
            competitorPosts.take(10).forEachIndexed { index, post ->
                append("${index + 1}. ${post.title}")
                if (post.description.isNotBlank()) append(" - ${post.description}")
                append("\n")
            }
            append("위 글들과 제목 구조·도입부·표현이 겹치지 않게 새로운 방식으로 써줘.\n\n")
        }

        append("[글쓰기 스타일 - ${style.number}. ${style.label}]\n")
        append("${style.guidance}\n\n")
        append("[이 스타일의 소제목 규칙]\n")
        append("${style.headingRule}으로 서로 겹치지 않는 소제목을 반드시 4개에서 6개 만들어줘. 각 소제목은 별도 줄에 쓰고 바로 아래에 그 소제목을 설명하는 본문을 붙여줘. 소제목 끝에는 문장부호를 붙이지 마.\n")
        // 스타일 지침에 예시로 든 소제목(예: 타임라인형의 "접수 내용", 스토리텔링형의 "문의
        // 내용")이 글의 맨 처음에 나오는 문구처럼 보여서, AI가 이걸 그대로 첫 줄로 쓰고 별도
        // 제목을 빠뜨리는 문제가 있었다(사용자 신고: "타임라인형 제목이 안들어가"). 위 스타일
        // 지침·소제목 규칙 바로 다음, 가장 최근 지시로 한 번 더 강하게 못박아서 어떤 스타일을
        // 골라도 첫 줄은 반드시 별도의 글 제목이어야 함을 분명히 한다.
        append("아주 중요 - 위 소제목 예시나 규칙이 무엇이든, 그건 전부 제목 다음에 오는 본문 안의 소제목이야. 이 스타일을 골랐다고 소제목 중 하나(예: 접수 내용, 문의 내용 같은 첫 단계)를 글의 맨 첫 줄로 쓰면 안 돼 - 글의 맨 첫 줄은 무조건 이 스타일과 무관한 별도의 제목 한 줄이어야 하고, 그 다음 빈 줄, 그 다음에야 이 스타일의 소제목들이 시작돼.\n\n")
        append("스타일 지침이 실제 입력 자료에 없는 경험, 수치, 시간, 원인, 결과를 요구할 경우 그 부분만 생략하고 2026 글쓰기 기준을 우선해 - 그렇다고 스타일 지침 전체를 무시하고 평범한 정보형 서술로 돌아가면 안 돼. " +
            "사실을 지어내지 않는 선에서도 문장 구조, 소제목 짓는 방식, 어투만으로 스타일 차이가 분명히 드러나야 해. 다른 스타일 번호를 골랐는데 글의 골격과 말투가 비슷하게 느껴지면 안 돼.\n\n")

        val voiceHeader = if (informational) "[이 블로그만의 문체 - 다른 블로그와 겹치지 않게 반드시 지켜줘]" else "[이 블로그($phone)만의 문체 - 다른 블로그와 겹치지 않게 반드시 지켜줘]"
        append(voiceHeader).append("\n")
        append("${blogProfile.voiceHint}\n")
        append("${blogProfile.openingStyle}\n\n")
        if (informational) {
            append("위 문체에 방문, 도착, 현장 작업, 고객 경험을 전제로 한 표현이 있으면 적용하지 말고 순수 정보형 서술을 유지해.\n")
        }
    }
